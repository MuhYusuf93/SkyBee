/// Additive physical-cash facts and bounded reconstructible balances.
final cashDrawerSchema = [
  '''CREATE TABLE cash_drawer_policy(id INTEGER PRIMARY KEY CHECK(id=1),
    mode TEXT NOT NULL DEFAULT 'off' CHECK(mode IN('off','notes','audit')),
    revision INTEGER NOT NULL DEFAULT 1 CHECK(typeof(revision)='integer' AND revision>0))''',
  'INSERT INTO cash_drawer_policy(id) VALUES(1)',
  '''CREATE TABLE cash_drawer_sessions(id TEXT PRIMARY KEY NOT NULL CHECK(length(id)=36),
    operation_key TEXT NOT NULL UNIQUE CHECK(length(trim(operation_key))>0),payload_hash TEXT NOT NULL CHECK(length(payload_hash)=64),
    store_day TEXT NOT NULL CHECK(length(store_day)=10),time_zone TEXT NOT NULL,
    session_number INTEGER NOT NULL CHECK(typeof(session_number)='integer' AND session_number>0),
    currency_code TEXT NOT NULL CHECK(currency_code IN('IDR','USD','MYR','EUR')),
    currency_scale INTEGER NOT NULL CHECK((currency_code='IDR' AND currency_scale=0) OR (currency_code IN('USD','MYR','EUR') AND currency_scale=2)),
    policy_mode TEXT NOT NULL CHECK(policy_mode IN('notes','audit')),
    opening_counts_json TEXT CHECK(opening_counts_json IS NULL OR length(opening_counts_json)<=16384),
    reason TEXT NOT NULL CHECK(length(reason)<=1000),
    created_at INTEGER NOT NULL CHECK(typeof(created_at)='integer' AND created_at>=0),
    UNIQUE(store_day,currency_code,session_number))''',
  '''CREATE TABLE cash_drawer_state(session_id TEXT PRIMARY KEY NOT NULL
    REFERENCES cash_drawer_sessions(id) ON DELETE RESTRICT,
    known INTEGER NOT NULL CHECK(known IN(0,1)),
    revision INTEGER NOT NULL DEFAULT 1 CHECK(typeof(revision)='integer' AND revision>0))''',
  '''CREATE TABLE cash_drawer_balances(session_id TEXT NOT NULL
    REFERENCES cash_drawer_sessions(id) ON DELETE RESTRICT,
    denomination INTEGER NOT NULL CHECK(typeof(denomination)='integer' AND denomination>0),
    piece_count INTEGER NOT NULL CHECK(typeof(piece_count)='integer' AND piece_count>0 AND piece_count<=1000000),
    PRIMARY KEY(session_id,denomination))''',
  '''CREATE TABLE cash_drawer_events(id TEXT PRIMARY KEY NOT NULL CHECK(length(id)=36),
    session_id TEXT NOT NULL REFERENCES cash_drawer_sessions(id) ON DELETE RESTRICT,
    sequence INTEGER NOT NULL CHECK(typeof(sequence)='integer' AND sequence>0),
    operation_key TEXT NOT NULL UNIQUE CHECK(length(trim(operation_key))>0),payload_hash TEXT NOT NULL CHECK(length(payload_hash)=64),
    kind TEXT NOT NULL CHECK(kind IN('movement','reconcile')),
    source_kind TEXT NOT NULL CHECK(source_kind IN('checkout','receivable','refund','supplier_payment','journal_in','journal_out','handover','journal_reversal','reconcile')),
    source_id TEXT NOT NULL CHECK(length(source_id)=36),
    cash_in_minor INTEGER NOT NULL CHECK(typeof(cash_in_minor)='integer' AND cash_in_minor>=0),
    cash_out_minor INTEGER NOT NULL CHECK(typeof(cash_out_minor)='integer' AND cash_out_minor>=0),
    in_counts_json TEXT NOT NULL CHECK(length(in_counts_json)<=16384),
    out_counts_json TEXT NOT NULL CHECK(length(out_counts_json)<=16384),
    before_counts_json TEXT CHECK(before_counts_json IS NULL OR length(before_counts_json)<=16384),
    observed_counts_json TEXT CHECK(observed_counts_json IS NULL OR length(observed_counts_json)<=16384),
    before_known INTEGER NOT NULL CHECK(before_known IN(0,1)),
    difference_minor INTEGER CHECK(difference_minor IS NULL OR typeof(difference_minor)='integer'),
    reason TEXT NOT NULL CHECK(length(reason)<=1000),
    created_at INTEGER NOT NULL CHECK(typeof(created_at)='integer' AND created_at>=0),
    UNIQUE(session_id,sequence),UNIQUE(source_kind,source_id))''',
  '''CREATE TABLE cash_drawer_closures(session_id TEXT PRIMARY KEY NOT NULL
    REFERENCES cash_drawer_sessions(id) ON DELETE RESTRICT,
    operation_key TEXT NOT NULL UNIQUE CHECK(length(trim(operation_key))>0),payload_hash TEXT NOT NULL CHECK(length(payload_hash)=64),
    revision INTEGER NOT NULL CHECK(typeof(revision)='integer' AND revision>0),
    expected_counts_json TEXT NOT NULL CHECK(length(expected_counts_json)<=16384),
    expected_known INTEGER NOT NULL CHECK(expected_known IN(0,1)),
    observed_counts_json TEXT CHECK(observed_counts_json IS NULL OR length(observed_counts_json)<=16384),
    difference_minor INTEGER CHECK(difference_minor IS NULL OR typeof(difference_minor)='integer'),
    owner_exception INTEGER NOT NULL DEFAULT 0 CHECK(owner_exception IN(0,1)),
    reason TEXT NOT NULL CHECK(length(reason)<=1000),
    created_at INTEGER NOT NULL CHECK(typeof(created_at)='integer' AND created_at>=0))''',
  'ALTER TABLE cart_drafts ADD COLUMN drawer_session_id TEXT REFERENCES cash_drawer_sessions(id) ON DELETE RESTRICT',
  'ALTER TABLE cart_drafts ADD COLUMN change_counts_json TEXT CHECK(change_counts_json IS NULL OR length(change_counts_json)<=16384)',
  'ALTER TABLE checkout_tenders ADD COLUMN change_counts_json TEXT CHECK(change_counts_json IS NULL OR length(change_counts_json)<=16384)',
  'ALTER TABLE payments ADD COLUMN cash_provenance_version INTEGER NOT NULL DEFAULT 0 CHECK(cash_provenance_version IN(0,1))',
  'ALTER TABLE sale_transactions ADD COLUMN drawer_version INTEGER NOT NULL DEFAULT 0 CHECK(drawer_version IN(0,1))',
  '''CREATE TABLE payment_cash_sources(payment_id TEXT PRIMARY KEY NOT NULL REFERENCES payments(id) ON DELETE RESTRICT,
    source TEXT NOT NULL CHECK(source IN('drawer','external','unknown')),
    policy_mode TEXT NOT NULL CHECK(policy_mode IN('off','notes','audit')),
    session_id TEXT REFERENCES cash_drawer_sessions(id) ON DELETE RESTRICT,
    event_id TEXT UNIQUE REFERENCES cash_drawer_events(id) ON DELETE RESTRICT,
    in_minor INTEGER CHECK(in_minor IS NULL OR (typeof(in_minor)='integer' AND in_minor>=0)),
    out_minor INTEGER CHECK(out_minor IS NULL OR (typeof(out_minor)='integer' AND out_minor>=0)),
    in_counts_json TEXT CHECK(in_counts_json IS NULL OR length(in_counts_json)<=16384),
    out_counts_json TEXT CHECK(out_counts_json IS NULL OR length(out_counts_json)<=16384),
    CHECK(source='drawer' OR (session_id IS NULL AND event_id IS NULL AND in_minor IS NULL AND out_minor IS NULL AND in_counts_json IS NULL AND out_counts_json IS NULL)),
    CHECK(event_id IS NULL OR (session_id IS NOT NULL AND in_minor IS NOT NULL AND out_minor IS NOT NULL AND in_counts_json IS NOT NULL AND out_counts_json IS NOT NULL)))''',
  'CREATE INDEX cash_drawer_sessions_date ON cash_drawer_sessions(store_day DESC,id COLLATE BINARY DESC)',
  'CREATE INDEX cash_drawer_events_period ON cash_drawer_events(created_at DESC,id COLLATE BINARY DESC)',
  for (final table in [
    'cash_drawer_sessions',
    'cash_drawer_events',
    'cash_drawer_closures',
    'payment_cash_sources',
  ]) ...[
    "CREATE TRIGGER ${table}_no_update BEFORE UPDATE ON $table BEGIN SELECT RAISE(ABORT,'immutable_fact'); END",
    "CREATE TRIGGER ${table}_no_delete BEFORE DELETE ON $table BEGIN SELECT RAISE(ABORT,'immutable_fact'); END",
  ],
];
