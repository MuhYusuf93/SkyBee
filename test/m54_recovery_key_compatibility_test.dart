import 'package:flutter_test/flutter_test.dart';
import 'package:kasir_app/core/domain/app_error.dart';
import 'package:kasir_app/core/security/recovery_mnemonic.dart';
import 'package:kasir_app/data/repositories/product_code_resolver.dart';
import 'package:kasir_app/features/backup/application/backup_service.dart';

void main() {
  test('M54 mnemonic keeps the independent legacy archive HKDF key', () async {
    const id = '01234567-89ab-cdef-0123-456789abcdef';
    final entropy = '0' * 64;
    final words = RecoveryMnemonic.entropyToMnemonic(entropy);
    // Python stdlib hmac/hashlib RFC5869 calculation, public zero-entropy test
    // input. This is not generated by the production Dart derivation.
    const expected =
        '58fb1fa05070e4bd9540b54c671d7592bfd8b2366cdd6ee2daa410b840d234a2';
    expect(await BackupService.portableDatabaseKey(entropy, id), expected);
    expect(await BackupService.portableDatabaseKey(words, id), expected);
    expect(BackupService.normalizeCode(words), entropy);
  });
  test('M54 business lookup refuses recovery QR before any database read', () {
    final qr = RecoveryMnemonic.recoveryQr(
      storeId: '01234567-89ab-cdef-0123-456789abcdef',
      entropy: '0' * 64,
    );
    for (final value in [qr, qr.toLowerCase()]) {
      expect(
        () => ProductCodeResolver.query(value),
        throwsA(
          isA<AppError>().having(
            (e) => e.message,
            'message',
            'm54RecoveryOnly',
          ),
        ),
      );
    }
    expect(
      () => RecoveryMnemonic.recoveryQr(storeId: '-' * 36, entropy: '0' * 64),
      throwsFormatException,
    );
  });
}
